#!/usr/bin/env python3
"""Generates unity/Assets/Scripts/City/CatalogData.cs from msp's scripts/catalog.gd and
art/specials.json, so the port's build menu stays msp's. Run from the repo root:
    python3 unity/tools/gen_catalog.py
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(ROOT, "scripts/catalog.gd")).read()

def block(name):
    m = re.search(r"^const %s := " % name, src, re.M)
    i = src.index("{", m.end() - 1) if src[m.end()] == "{" else src.index("[", m.end() - 1)
    open_c = src[i]; close_c = "}" if open_c == "{" else "]"
    depth = 0
    for j in range(i, len(src)):
        if src[j] == open_c: depth += 1
        elif src[j] == close_c:
            depth -= 1
            if depth == 0: return src[i:j + 1]

colors = dict(re.findall(r"^const ([A-Z_]+) := (Color\([^)]*\))", src, re.M))

def to_py(text):
    text = re.sub(r"#[^\n]*", "", text)
    for k, v in colors.items():
        text = re.sub(r"\b%s\b" % k, v, text)
    text = re.sub(r"Color\(([^)]*)\)", lambda m: "[" + m.group(1) + "]", text)
    text = text.replace("true", "True").replace("false", "False")
    return eval(text)

defs = to_py(block("DEFS"))
defaults = to_py(block("DEFAULTS"))
tiers = to_py(block("TIERS"))
art = {e["id"]: e for e in json.load(open(os.path.join(ROOT, "art/specials.json")))["specials"]}

def cs_str(s): return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'
def cs_col(c): return "new Color(%sf, %sf, %sf)" % tuple(repr(float(x)) for x in c[:3])
def cs_f(x): return repr(float(x)) + "f"

lines = []
for id_, d0 in defs.items():
    d = dict(defaults); d.update(d0)
    a = art.get(id_, {})
    model = d.get("model", "") or (a.get("model") or "") or ("res://assets/kit/specials/%s.glb" % id_)
    kit = ""
    if model.startswith("res://assets/kit/") and os.path.exists(os.path.join(ROOT, model[6:])):
        rel = model[len("res://assets/kit/"):-len(".glb")]
        sub, f = rel.split("/", 1)
        kit = f if sub in ("buildings", "roads", "props", "cars") else rel
    door = a.get("door")
    door_cs = "null" if not isinstance(door, dict) else "new Door(%s, %s, %s)" % (cs_f(door.get("x", 0)), cs_f(door.get("z", 0)), cs_f(door.get("yaw_deg", 0)))
    lines.append(
        "            new Def { id = %s, name = %s, group = %s, size = %d, cost = %d, upkeep = %s, tier = %d, tags = new[] { %s }, "
        "unique = %s, needsRoad = %s, placement = %s, menu = %s, interior = %s, unlockHint = %s, desc = %s, unlockPop = %d, "
        "accent = %s, standIn = %s, color = %s, height = %s, kitModel = %s, door = %s },"
        % (cs_str(id_), cs_str(d["name"]), cs_str(d["group"]), d["size"], d["cost"], cs_f(d["upkeep"]), d["tier"],
           ", ".join(cs_str(t) for t in d["tags"]), str(d["unique"]).lower(), str(d["needs_road"]).lower(),
           cs_str(d["placement"]), str(d["menu"]).lower(), cs_str(d["interior"]), cs_str(d["unlock_hint"]), cs_str(d["desc"]),
           d["unlock_pop"], cs_col(d["accent"]), cs_str(d["stand_in"]), cs_col(d["color"]), cs_f(d["height"]), cs_str(kit), door_cs))

tier_lines = []
for t in tiers:
    g = t["goals"]
    tier_lines.append("            new Tier { name = %s, pop = %d, income = %d, any = %s }," % (
        cs_str(t["name"]), g.get("pop", 0), g.get("income", 0), str(t.get("any", False)).lower()))

out = """// Generated by unity/tools/gen_catalog.py from msp's scripts/catalog.gd and art/specials.json.
// Don't edit by hand: change msp and run the tool again.
using UnityEngine;

namespace MSP
{
    public static partial class Catalog
    {
        public static readonly Def[] DEFS =
        {
%s
        };

        public static readonly Tier[] TIERS =
        {
%s
        };
    }
}
""" % ("\n".join(lines), "\n".join(tier_lines))
dst = os.path.join(ROOT, "unity/Assets/Scripts/City/CatalogData.cs")
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, "w").write(out)
print("wrote", dst, len(lines), "defs")
